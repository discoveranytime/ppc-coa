"""Fetch a first-page preview image for every link record and save it under
assets/link-previews/<record-id>.jpg, plus assets/link-previews/manifest
as window.PPC_PREVIEWS (record id -> true) for the detail page to check.

Sources (public documents, supplied by Victor):
- Janoshik verify/main pages: the page HTML exposes ./img/<hash>.png, the
  full report scan. Download it directly (no re-render needed).
- Freedom Diagnostics PDFs: download the PDF, render page 1 with pdftoppm.

Previews are resized to max 1000px wide, JPEG quality 82. Nothing is
transcribed here; the preview is a picture of the lab's own document and
the detail page links it out to the original.
"""
import json
import re
import subprocess
import sys
import tempfile
import urllib.request
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "assets" / "link-previews"
OUT.mkdir(parents=True, exist_ok=True)
UA = {"User-Agent": "Mozilla/5.0 (X11; Linux x86_64) PPC-COA-Preview/1.0"}


def fetch(url, timeout=60):
    req = urllib.request.Request(url, headers=UA)
    with urllib.request.urlopen(req, timeout=timeout) as r:
        return r.read()


def save_preview(img_bytes, rec_id):
    with tempfile.NamedTemporaryFile(suffix=".bin", delete=False) as t:
        t.write(img_bytes)
        tmp = t.name
    try:
        with Image.open(tmp) as im:
            im = im.convert("RGB")
            if im.width > 1000:
                im = im.resize((1000, int(im.height * 1000 / im.width)), Image.LANCZOS)
            im.save(OUT / f"{rec_id}.jpg", "JPEG", quality=82, optimize=True)
    finally:
        Path(tmp).unlink(missing_ok=True)


def janoshik_preview(url):
    html = fetch(url).decode("utf-8", "ignore")
    # Report scan: relative ./img/<hash>.png on the verify page.
    m = re.search(r'src="(\./img/[^"]+\.png)"', html)
    if not m:
        # Fallback: any same-host /img/ png.
        m = re.search(r'src="([^"]*/img/[^"]+\.png)"', html)
    if not m:
        raise ValueError("no report image found in page")
    src = m.group(1)
    if src.startswith("./"):
        base = url.rsplit("/", 1)[0]
        src = base + src[1:]
    elif src.startswith("/"):
        base = "/".join(url.split("/")[:3])
        src = base + src
    return fetch(src)


def freedom_preview(url):
    pdf = fetch(url)
    with tempfile.TemporaryDirectory() as d:
        p = Path(d) / "doc.pdf"
        p.write_bytes(pdf)
        subprocess.run(["pdftoppm", "-jpeg", "-r", "130", "-f", "1", "-l", "1",
                        str(p), str(Path(d) / "page")],
                       check=True, capture_output=True)
        pages = sorted(Path(d).glob("page-*.jpg"))
        if not pages:
            raise ValueError("pdftoppm produced no pages")
        return pages[0].read_bytes()


def process(rec):
    url = rec["sourceUrl"]
    try:
        if "janoshik" in url:
            img = janoshik_preview(url)
        elif "freedomdiagnosticstesting" in url:
            img = freedom_preview(url)
        else:
            return rec["id"], "SKIP unknown host"
        save_preview(img, rec["id"])
        return rec["id"], "OK"
    except Exception as e:  # noqa: BLE001 - report per record, keep going
        return rec["id"], f"FAIL {type(e).__name__}: {e}"


def main():
    js = (ROOT / "link-records.js").read_text()
    records = json.loads(js[js.index("["):js.rindex("]") + 1])
    results = {}
    with ThreadPoolExecutor(max_workers=8) as ex:
        for rec_id, status in ex.map(process, records):
            results[rec_id] = status
            print(f"{rec_id}: {status}", flush=True)
    ok = [k for k, v in results.items() if v == "OK"]
    bad = {k: v for k, v in results.items() if v != "OK"}
    manifest = ("// Generated by tools/build-link-previews.py — record ids with a\n"
                "// locally hosted first-page preview image.\n"
                "window.PPC_PREVIEWS = " + json.dumps({k: True for k in sorted(ok)}) + ";\n")
    (OUT / "manifest.js").write_text(manifest)
    total_mb = sum(p.stat().st_size for p in OUT.glob("*.jpg")) / 1e6
    print(f"\nOK: {len(ok)}/{len(records)}  total preview size: {total_mb:.1f} MB")
    if bad:
        print("FAILURES:")
        for k, v in bad.items():
            print(f"  {k}: {v}")
        sys.exit(1)


if __name__ == "__main__":
    main()
